const assert=require('node:assert/strict');
const C=require('./core.js');
const s=C.fresh();
const original=JSON.stringify(s);
const base=C.previewExerciseLibrary(s);
assert.equal(base.audit.collisions.length,0);
assert.equal(base.audit.missing.length,0);
assert.equal(JSON.stringify(s),original,'audit must not mutate');
s.days['2026-10-11']={sessions:[{id:'a',items:[{id:'bench',name:'DBベンチプレス',kind:'strength',sets:[{kg:14,reps:12,done:true}]}]}]};
assert.equal(C.previous(s,'bench','2026-10-13').item.sets[0].kg,14);
const before=JSON.stringify(s);
assert.equal(C.previewExerciseLibrary(s).audit.collisions.length,0);
assert.equal(JSON.stringify(s),before);
s.templates.push({id:'custom',name:'カール',items:[{id:'bench',name:'DBカール',kind:'strength'}]});
const flagged=C.previewExerciseLibrary(s);
assert(flagged.audit.collisions.some(x=>x.id==='bench'));
assert(!flagged.exercises.some(x=>x.id==='bench'),'ambiguous ID must not be auto-merged');
assert.equal(C.previous(s,'bench','2026-10-13').item.sets[0].kg,14,'legacy previous lookup unchanged');
assert.equal(JSON.stringify(s),JSON.stringify(s),'no mutation');
const twice=C.previewExerciseLibrary(s);
assert.deepEqual(twice,flagged,'idempotent preview');
console.log('PASS: 8 assertions; standard IDs, non-mutation, previous record, collision, idempotence');

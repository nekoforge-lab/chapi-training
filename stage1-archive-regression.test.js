const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const C=require('./core.js');
const source=fs.readFileSync(__dirname+'/app.js','utf8');
const a=source.indexOf('function archivedIds('), b=source.indexOf('function librarySave(',a);
assert(a>=0&&b>a);
const store=C.fresh();const t=store.templates.find(t=>t.items.some(i=>i.kind==='strength'));
const exercise=t.items.find(i=>i.kind==='strength');
const id=exercise.id;
store.days['2026-10-11']={sessions:[{id:'historical',items:[{...C.clone(exercise),sets:[{kg:14,reps:12,done:true}]}]}]};
const history=JSON.stringify(store.days);
const ctx=vm.createContext({C,store,Set});
vm.runInContext(source.slice(a,b)+';this.archivedIds=archivedIds;this.activeTemplateItems=activeTemplateItems;',ctx);
assert(ctx.activeTemplateItems(t,'strength').some(i=>i.id===id));
store.exerciseLibrary=[{id,name:exercise.name,kind:'strength',archived:true}];
assert(ctx.archivedIds().has(id));
assert(!ctx.activeTemplateItems(t,'strength').some(i=>i.id===id));
assert(t.items.some(i=>i.id===id),'preset source preserved');
assert.equal(JSON.stringify(store.days),history,'historical snapshot preserved');
assert.equal(C.previous(store,id,'2026-10-13').item.sets[0].kg,14);
store.exerciseLibrary[0].archived=false;
assert(ctx.activeTemplateItems(t,'strength').some(i=>i.id===id),'restored to original preset');
assert.equal(JSON.stringify(store.days),history);
console.log('PASS: archive hides from new sessions, restores preset, preserves history and previous weight');
